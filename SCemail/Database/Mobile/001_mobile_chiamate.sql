-- Dispositivi registrati (uno per installazione dell'app).
CREATE TABLE SGAPP.MOBILE_DISPOSITIVI (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DEVICE_UUID      VARCHAR2(36)   NOT NULL,
    NOME             VARCHAR2(100)  NOT NULL,
    PROPRIETARIO     VARCHAR2(100)  NOT NULL,
    NUMERO_SIM       VARCHAR2(30),
    ATTIVO           NUMBER(1)      DEFAULT 1 NOT NULL,
    -- SHA-256 (hex) del token operativo: il token in chiaro esiste solo sul telefono.
    TOKEN_HASH       VARCHAR2(64)   NOT NULL,
    APP_VERSION      VARCHAR2(30),
    ANDROID_VERSION  VARCHAR2(30),
    MODELLO          VARCHAR2(100),
    ULTIMO_CONTATTO  TIMESTAMP,
    CREATED_AT       TIMESTAMP      DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    UPDATED_AT       TIMESTAMP      DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT PK_MOBILE_DISPOSITIVI PRIMARY KEY (ID),
    CONSTRAINT UQ_MOB_DISP_UUID      UNIQUE (DEVICE_UUID),
    CONSTRAINT UQ_MOB_DISP_TOKEN     UNIQUE (TOKEN_HASH),
    CONSTRAINT CK_MOB_DISP_ATTIVO    CHECK (ATTIVO IN (0, 1))
);

-- Codici di attivazione monouso generati dall'amministratore.
-- DISPOSITIVO_ID valorizzato alla creazione = riassociazione di un dispositivo
-- esistente (es. app reinstallata): lo storico chiamate resta sullo stesso ID.
CREATE TABLE SGAPP.MOBILE_ATTIVAZIONI (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODICE_HASH      VARCHAR2(64)   NOT NULL,
    DESCRIZIONE      VARCHAR2(200),
    CREATO_DA        VARCHAR2(100)  NOT NULL,
    CREATED_AT       TIMESTAMP      DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    SCADENZA         TIMESTAMP      NOT NULL,
    DISPOSITIVO_ID   NUMBER,
    USATO_AT         TIMESTAMP,
    USATO_DA_UUID    VARCHAR2(36),
    REVOCATO         NUMBER(1)      DEFAULT 0 NOT NULL,
    CONSTRAINT PK_MOBILE_ATTIVAZIONI PRIMARY KEY (ID),
    CONSTRAINT UQ_MOB_ATT_CODICE     UNIQUE (CODICE_HASH),
    CONSTRAINT FK_MOB_ATT_DISP       FOREIGN KEY (DISPOSITIVO_ID) REFERENCES SGAPP.MOBILE_DISPOSITIVI (ID),
    CONSTRAINT CK_MOB_ATT_REVOCATO   CHECK (REVOCATO IN (0, 1))
);

CREATE INDEX SGAPP.IX_MOB_ATT_DISP ON SGAPP.MOBILE_ATTIVAZIONI (DISPOSITIVO_ID);

-- Chiamate rilevate. EVENT_UUID è generato dal telefono ed è la chiave di idempotenza.
-- VERSIONE: un retry con versione <= a quella salvata non sovrascrive i dati.
CREATE TABLE SGAPP.MOBILE_CHIAMATE (
    ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EVENT_UUID         VARCHAR2(36)   NOT NULL,
    DISPOSITIVO_ID     NUMBER         NOT NULL,
    NUMERO_CHIAMANTE   VARCHAR2(40),               -- NULL = privato / sconosciuto
    PRESENTAZIONE      VARCHAR2(12)   NOT NULL,    -- VISIBILE, PRIVATO, SCONOSCIUTO, PUBBLICO
    DIREZIONE          VARCHAR2(10)   NOT NULL,    -- INCOMING, OUTGOING, UNKNOWN
    ESITO              VARCHAR2(10)   NOT NULL,    -- ANSWERED, MISSED, REJECTED, UNKNOWN
    TIPO_ORIGINALE     NUMBER(3),                  -- CallLog.Calls.TYPE, per diagnostica
    DATA_INIZIO        TIMESTAMP      NOT NULL,
    DATA_FINE          TIMESTAMP,
    DURATA_SECONDI     NUMBER(10)     DEFAULT 0 NOT NULL,
    ACCOUNT_TELEFONICO VARCHAR2(100),              -- PHONE_ACCOUNT_ID (SIM), se disponibile
    VERSIONE           NUMBER(10)     DEFAULT 1 NOT NULL,
    CREATED_AT         TIMESTAMP      DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    UPDATED_AT         TIMESTAMP      DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT PK_MOBILE_CHIAMATE      PRIMARY KEY (ID),
    CONSTRAINT UQ_MOB_CHIAM_EVENT      UNIQUE (EVENT_UUID),
    CONSTRAINT FK_MOB_CHIAM_DISP       FOREIGN KEY (DISPOSITIVO_ID) REFERENCES SGAPP.MOBILE_DISPOSITIVI (ID),
    CONSTRAINT CK_MOB_CHIAM_DIREZIONE  CHECK (DIREZIONE IN ('INCOMING', 'OUTGOING', 'UNKNOWN')),
    CONSTRAINT CK_MOB_CHIAM_ESITO      CHECK (ESITO IN ('ANSWERED', 'MISSED', 'REJECTED', 'UNKNOWN')),
    CONSTRAINT CK_MOB_CHIAM_PRES       CHECK (PRESENTAZIONE IN ('VISIBILE', 'PRIVATO', 'SCONOSCIUTO', 'PUBBLICO')),
    CONSTRAINT CK_MOB_CHIAM_DURATA     CHECK (DURATA_SECONDI >= 0),
    CONSTRAINT CK_MOB_CHIAM_VERSIONE   CHECK (VERSIONE >= 1)
);

-- Consultazione tipica: chiamate di un dispositivo in un periodo.
CREATE INDEX SGAPP.IX_MOB_CHIAM_DISP_DATA   ON SGAPP.MOBILE_CHIAMATE (DISPOSITIVO_ID, DATA_INIZIO);
-- Consultazione tipica: chiamate perse/risposte in un periodo, tutti i dispositivi.
CREATE INDEX SGAPP.IX_MOB_CHIAM_ESITO_DATA  ON SGAPP.MOBILE_CHIAMATE (ESITO, DATA_INIZIO);
-- Ricerca per numero chiamante.
CREATE INDEX SGAPP.IX_MOB_CHIAM_NUMERO      ON SGAPP.MOBILE_CHIAMATE (NUMERO_CHIAMANTE);

COMMENT ON TABLE SGAPP.MOBILE_DISPOSITIVI IS 'Telefoni aziendali registrati con l''app Call Registry';
COMMENT ON TABLE SGAPP.MOBILE_ATTIVAZIONI IS 'Codici di attivazione monouso (solo hash)';
COMMENT ON TABLE SGAPP.MOBILE_CHIAMATE    IS 'Chiamate rilevate dai telefoni, date in UTC, idempotenza su EVENT_UUID';
